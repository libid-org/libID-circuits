"""The identity circuits' platform table.

`lib/identity/platforms.json` holds each platform's node tags, buffers and id
shape; `lib/identity/handles.json` the shared vectors. This script generates
`lib/identity/src/table.nr` (the constants every circuit compiles) and
`table_tests.nr` (one test per vector) from them, and lends the witness
scripts the constants read back from the Noir sources and the encodings they
share.

    scripts/identity_table.py          # write table.nr and table_tests.nr
    scripts/identity_table.py --check  # exit non-zero when either differs from its sources

Writing needs nargo on PATH: the Noir is formatted before it is compared or written.
"""
from __future__ import annotations

import argparse
import functools
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parent.parent
IDENTITY = ROOT / "lib" / "identity"
PLATFORMS = IDENTITY / "platforms.json"
HANDLES = IDENTITY / "handles.json"
TABLE = IDENTITY / "src" / "table.nr"
TABLE_TESTS = IDENTITY / "src" / "table_tests.nr"
LIB = IDENTITY / "src" / "lib.nr"
OIDC_GOOGLE = ROOT / "circuits" / "oidc-google" / "src" / "main.nr"

BANNER = [
    "Generated by scripts/identity_table.py. Do not edit.",
    "The sources are lib/identity/platforms.json and lib/identity/handles.json.",
]


# --- The Noir sources, read back ----------------------------------------------


@functools.cache
def constant(name: str, source: pathlib.Path = TABLE) -> str:
    """The right-hand side of `[pub] global <name>`, whitespace collapsed."""
    # nargo fmt wraps long constants, so read the declaration whole.
    found = re.search(rf"\bglobal\s+{re.escape(name)}\s*:[^=]*=\s*([^;]*);", source.read_text())
    if found is None:
        raise SystemExit(f"{source}: no `global {name}`; regenerate or check the name")
    return " ".join(found.group(1).split())


def integer(name: str, source: pathlib.Path = TABLE) -> int:
    return int(constant(name, source))


def byte_array(name: str, source: pathlib.Path = TABLE) -> bytes:
    inner = constant(name, source).strip("[]")
    return bytes(int(b, 16) for b in inner.split(",") if b.strip())


# --- Encodings the witness scripts share --------------------------------------


def fold(value: bytes) -> bytes:
    """A-Z down to a-z, every other byte unchanged: lib.nr's `fold_handle`."""
    return bytes(b + 0x20 if 0x41 <= b <= 0x5A else b for b in value)


def packed_tag(tag: bytes) -> int:
    """A tag as bearer-link's public input: its bytes from the top of a Field."""
    return int.from_bytes(tag.ljust(integer("MAX_TAG_LEN", LIB), b"\0"), "big")


def halves(digest: bytes) -> tuple[int, int]:
    """A 32-byte digest as the circuits' `[high, low]` 16-byte big-endian halves."""
    return int.from_bytes(digest[:16], "big"), int.from_bytes(digest[16:], "big")


def padded(name: str, value: bytes, size: int) -> list[int]:
    """`value` in a `size`-byte circuit buffer, the tail zero."""
    if len(value) > size:
        raise SystemExit(f"`{name}`: {len(value)} bytes do not fit the circuit's {size}-byte buffer")
    return list(value) + [0] * (size - len(value))


def toml_array(values, *, quoted: bool = False) -> str:
    """A Prover.toml array. Strings are always quoted, numbers when `quoted`."""
    return "[" + ", ".join(f'"{v}"' if quoted or isinstance(v, str) else str(v) for v in values) + "]"


# --- The sources --------------------------------------------------------------

# A platform key names constants (`HANDLE_TAG_X`) and test functions (`handle_x_0`).
PLATFORM_KEY = re.compile(r"[a-z][a-z0-9_]*")
# A tag as a literal in Noir, Rust, TypeScript and Solidity alike: no quote,
# backslash or space.
TAG = re.compile(r"[A-Za-z0-9._~:/?#\[\]@!$&*+,;=%-]+")
ID_SHAPES = ("decimal", "string")


def platforms() -> list[dict[str, Any]]:
    """Every platform in platforms.json, refused when a value no circuit or
    consumer can carry: a tag empty, past MAX_TAG_LEN or overlapping another,
    a buffer that is not a positive integer, an id shape the circuits lack."""
    doc = json.loads(PLATFORMS.read_text(encoding="utf-8"))
    out = doc["platforms"]
    max_tag = integer("MAX_TAG_LEN", LIB)
    seen: set[str] = set()
    for p in out:
        key = p["platform"]
        if not PLATFORM_KEY.fullmatch(key):
            raise SystemExit(f"ERROR: platform {key!r} must be lowercase ASCII")
        if key in seen:
            raise SystemExit(f"ERROR: {key!r} appears twice")
        seen.add(key)
        for tag in (p["userIdTag"], p["handleTag"]):
            if not TAG.fullmatch(tag):
                raise SystemExit(f"ERROR: tag {tag!r} carries a character a literal cannot hold")
            if len(tag.encode()) > max_tag:
                raise SystemExit(f"ERROR: tag {tag!r} must be 1 to {max_tag} bytes (lib.nr's MAX_TAG_LEN)")
        if p["idShape"] not in ID_SHAPES:
            raise SystemExit(f"ERROR: {key!r} idShape {p['idShape']!r} is not one of {ID_SHAPES}")
        for field in ("maxHandle", "maxId"):
            if not (isinstance(p[field], int) and p[field] > 0):
                raise SystemExit(f"ERROR: {key!r} {field} must be a positive integer")
    tags = [t for p in out for t in (p["userIdTag"], p["handleTag"])]
    for i, a in enumerate(tags):
        for b in tags[i + 1 :]:
            if a.startswith(b) or b.startswith(a):
                raise SystemExit(f"ERROR: tags {a!r} and {b!r} overlap; tags must be distinct and prefix-free")
    return out


def fold_byte(b: int) -> int:
    """A-Z down to a-z; every other byte unchanged."""
    return b + 0x20 if 0x41 <= b <= 0x5A else b


def check_vectors(spec: dict[str, Any], table: list[dict[str, Any]]) -> None:
    """Refuse a vector of a platform the table lacks, an accepted output that
    is not the fold of its input, or a stored node that is not
    SHA256(tag || value); a refused vector carries no node."""
    tags = {p["platform"]: p for p in table}
    for vec in spec["vectors"] + spec["idVectors"]:
        if vec["platform"] not in tags:
            raise SystemExit(f"ERROR: vector {vec['input']!r} names {vec['platform']!r}, which platforms.json lacks")
    for vec in spec["vectors"]:
        folded = bytes(fold_byte(b) for b in vec["input"].encode())
        if "output" in vec and vec["output"].encode() != folded:
            raise SystemExit(
                f"ERROR: {vec['platform']} {vec['input']!r}: output {vec['output']!r} is not its input folded"
            )
    cases = [(vec, "handleTag", "handleNode", vec.get("output")) for vec in spec["vectors"]] + [
        (vec, "userIdTag", "idNode", None if "error" in vec else vec["input"]) for vec in spec["idVectors"]
    ]
    for vec, tag, field, value in cases:
        if value is None:
            if field in vec:
                raise SystemExit(f"ERROR: refused {vec['platform']} {vec['input']!r} carries {field}")
            continue
        want = "0x" + hashlib.sha256((tags[vec["platform"]][tag] + value).encode()).hexdigest()
        if vec.get(field) != want:
            raise SystemExit(
                f"ERROR: {vec['platform']} {vec['input']!r}: {field} is not "
                f"SHA256(tag || value); expected {want}"
            )


def error_index(errors: list[dict[str, Any]], key: str) -> int:
    for i, err in enumerate(errors):
        if err["key"] == key:
            return i
    raise SystemExit(f"ERROR: unknown error kind {key!r} in a vector")


# --- The Noir -----------------------------------------------------------------

NOIR_ERRORS = {
    "Empty": "is empty",
    "TooLong": "too long",
    "BadCharacter": "byte not allowed",
}

NOIR_ESCAPES = {0x09: "\\t", 0x0A: "\\n", 0x22: '\\"'}


def header() -> str:
    return "".join(f"// {line}\n" for line in BANNER)


def noir_bytes(value: bytes) -> str:
    return "[" + ", ".join(f"0x{b:02x}" for b in value) + "]"


def noir_string(value: bytes) -> str | None:
    """`value` as a Noir string literal, or None when it holds a byte a
    literal cannot spell plainly: a backslash, a control byte other than tab
    and newline, or anything above 0x7e."""
    out = []
    for b in value:
        if b in NOIR_ESCAPES:
            out.append(NOIR_ESCAPES[b])
        elif 0x20 <= b <= 0x7E and b != 0x5C:
            out.append(chr(b))
        else:
            return None
    return '"' + "".join(out) + '"'


def noir_halves(node: str) -> str:
    """A node from the table as the `[high, low]` Fields `node_halves` returns."""
    return f"[0x{node[2:34]}, 0x{node[34:]}]"


def gen_table(table: list[dict[str, Any]], digest: str) -> str:
    """The circuit library's constants: what every circuit compiles against."""
    lines = [
        header().rstrip("\n"),
        "",
        "// Platform tags and buffers, for the identity circuits. The transform is",
        "// lib.nr's; table_tests.nr runs it against the shared vector table.",
        "",
        "/// SHA-256 of the handles.json this file was generated from.",
        f'pub global TABLE_SHA256: str<64> = "{digest}";',
        "",
    ]
    for p in table:
        name = p["platform"].upper()
        id_tag = p["userIdTag"].encode()
        handle_tag = p["handleTag"].encode()
        lines += [
            f"/// `{p['userIdTag']}`",
            f"pub global USER_ID_TAG_{name}: [u8; {len(id_tag)}] = {noir_bytes(id_tag)};",
            f"/// `{p['handleTag']}`",
            f"pub global HANDLE_TAG_{name}: [u8; {len(handle_tag)}] = {noir_bytes(handle_tag)};",
            f"pub global MAX_HANDLE_{name}: u32 = {p['maxHandle']};",
            f"pub global MAX_ID_{name}: u32 = {p['maxId']};",
            f"pub global ID_DECIMAL_{name}: bool = {str(p['idShape'] == 'decimal').lower()};",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def gen_table_tests(table: list[dict[str, Any]], spec: dict[str, Any], digest: str) -> str:
    """One Noir test per vector, run against lib.nr's algorithm.

    A refused vector is a `should_fail_with` test on the reason every other
    language gives. A value longer than the platform allows does not fit the
    circuit's buffer at all; its test hands the buffer's worth of bytes with
    the true length, which is the claim a dishonest witness would make.
    """
    by_key = {p["platform"]: p for p in table}
    lines = [
        header().rstrip("\n"),
        f"// Table SHA-256: {digest} (table::TABLE_SHA256).",
        "",
        "// The shared vector table, run against lib.nr's algorithm.",
        "",
        "use crate::{check_id, fixed_node_halves, fold_handle, node_halves, table, tag_of};",
        "use crate::testing::padded;",
        "",
    ]

    def buffer(value: bytes, size: int) -> list[str]:
        """The padded witness, as a string literal when one spells it."""
        kept = value[:size]
        literal = noir_string(kept)
        if literal is not None:
            return [f"    let raw: [u8; {size}] = padded({literal}.as_bytes());"]
        return [
            f"    // {json.dumps(value.decode(), ensure_ascii=False)}",
            f"    let raw: [u8; {size}] = {noir_bytes(kept + bytes(size - len(kept)))};",
        ]

    for i, vec in enumerate(spec["vectors"]):
        name = vec["platform"].upper()
        size = by_key[vec["platform"]]["maxHandle"]
        raw = vec["input"].encode()
        attr = "#[test]"
        if "error" in vec:
            attr = f'#[test(should_fail_with = "handle {NOIR_ERRORS[vec["error"]]}")]'
        lines.append(attr)
        lines.append(f"fn handle_{vec['platform']}_{i}() {{")
        lines += buffer(raw, size)
        lines.append(f"    let out = fold_handle(raw, {len(raw)});")
        if "output" in vec:
            lines.append(f"    let (tag, tag_len) = tag_of(table::HANDLE_TAG_{name});")
            lines.append(
                f"    assert(node_halves(tag, tag_len, out, {len(raw)})"
                f" == {noir_halves(vec['handleNode'])});"
            )
            lines.append(
                f"    assert(fixed_node_halves(table::HANDLE_TAG_{name}, out, {len(raw)})"
                f" == {noir_halves(vec['handleNode'])});"
            )
        else:
            lines.append("    let _ = out;")
        lines.append("}")
        lines.append("")

    for i, vec in enumerate(spec["idVectors"]):
        name = vec["platform"].upper()
        size = by_key[vec["platform"]]["maxId"]
        raw = vec["input"].encode()
        attr = "#[test]"
        if "error" in vec:
            attr = f'#[test(should_fail_with = "id {NOIR_ERRORS[vec["error"]]}")]'
        lines.append(attr)
        lines.append(f"fn id_{vec['platform']}_{i}() {{")
        lines += buffer(raw, size)
        lines.append(f"    check_id(raw, {len(raw)}, table::ID_DECIMAL_{name});")
        if "idNode" in vec:
            lines.append(f"    let (tag, tag_len) = tag_of(table::USER_ID_TAG_{name});")
            lines.append(
                f"    assert(node_halves(tag, tag_len, raw, {len(raw)})"
                f" == {noir_halves(vec['idNode'])});"
            )
            lines.append(
                f"    assert(fixed_node_halves(table::USER_ID_TAG_{name}, raw, {len(raw)})"
                f" == {noir_halves(vec['idNode'])});"
            )
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def formatted(files: dict[str, str]) -> dict[str, str]:
    """`files` (name -> Noir source) run through `nargo fmt` as one package,
    so what is compared or written is what CI's `nargo fmt --check` accepts."""
    nargo = shutil.which("nargo")
    if nargo is None:
        print("ERROR: nargo is not on PATH, so the Noir cannot be formatted", file=sys.stderr)
        raise SystemExit(1)
    with tempfile.TemporaryDirectory() as tmp:
        package = pathlib.Path(tmp)
        src = package / "src"
        src.mkdir()
        (package / "Nargo.toml").write_text(
            '[package]\nname = "table"\ntype = "lib"\nauthors = [""]\n[dependencies]\n'
        )
        (src / "lib.nr").write_text("".join(f"mod {name};\n" for name in files))
        for name, text in files.items():
            (src / f"{name}.nr").write_text(text, encoding="utf-8")
        done = subprocess.run([nargo, "fmt"], cwd=package, capture_output=True, text=True)
        if done.returncode != 0:
            print(f"ERROR: nargo fmt failed:\n{done.stderr}", file=sys.stderr)
            raise SystemExit(1)
        return {name: (src / f"{name}.nr").read_text(encoding="utf-8") for name in files}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit non-zero when a generated file differs from its sources.",
    )
    args = parser.parse_args()

    table = platforms()
    # Explicit encoding: handles.json holds non-ASCII, and the ambient locale
    # decides otherwise on a machine configured differently.
    raw = HANDLES.read_bytes()
    spec = json.loads(raw.decode("utf-8"))
    check_vectors(spec, table)
    digest = hashlib.sha256(raw).hexdigest()

    generated = formatted({
        TABLE.stem: gen_table(table, digest),
        TABLE_TESTS.stem: gen_table_tests(table, spec, digest),
    })
    outputs = [(TABLE, generated[TABLE.stem]), (TABLE_TESTS, generated[TABLE_TESTS.stem])]

    if args.check:
        stale = [
            path
            for path, text in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("ERROR: generated files differ from their sources. Run scripts/identity_table.py", file=sys.stderr)
            for path in stale:
                print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"lib/identity's table is what platforms.json and handles.json ({digest}) generate")
        return 0

    for path, text in outputs:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
