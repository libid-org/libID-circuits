"""The identity circuits' platform table.

`lib/identity/platforms.json` holds each platform's node tags, buffers and id
shape; `lib/identity/handles.json` the shared vectors. This script generates
`lib/identity/src/table.nr` (the constants every circuit compiles) and
`table_tests.nr` (one test per vector) from them, and lends the witness
scripts the typed JSON loader, the constants read back from the Noir sources
and the encodings they share.

    scripts/identity_table.py          # write table.nr and table_tests.nr
    scripts/identity_table.py --check  # exit non-zero when either differs from its sources

Both need nargo on PATH: the Noir is formatted before it is compared or written.
"""
from __future__ import annotations

import argparse
import dataclasses
import functools
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import typing

ROOT = pathlib.Path(__file__).resolve().parent.parent
IDENTITY = ROOT / "lib" / "identity"
PLATFORMS = IDENTITY / "platforms.json"
HANDLES = IDENTITY / "handles.json"
TABLE = IDENTITY / "src" / "table.nr"
TABLE_TESTS = IDENTITY / "src" / "table_tests.nr"
LIB = IDENTITY / "src" / "lib.nr"
OIDC_GOOGLE = ROOT / "circuits" / "oidc-google" / "src" / "main.nr"

BANNER = [
    "Generated by scripts/identity_table.py. Do not edit.",
    "The sources are lib/identity/platforms.json and lib/identity/handles.json.",
]

T = typing.TypeVar("T")


# --- JSON as typed documents --------------------------------------------------


def of_json(cls: type[T], doc: object, where: str) -> T:
    """`doc` as the dataclass `cls`: one member per field, nested dataclasses
    and lists of them recursively, a field with a default taking it when the
    member is absent, members the class does not declare ignored. `where`
    names the document in a refusal."""
    fields = dataclasses.fields(cls)
    if not isinstance(doc, dict):
        raise SystemExit(f"{where}: expected an object with {', '.join(f.name for f in fields)}")
    hints = typing.get_type_hints(cls)
    members = {}
    for field in fields:
        if field.name in doc:
            members[field.name] = typed(hints[field.name], doc[field.name], f"{where}.{field.name}")
        elif field.default is not dataclasses.MISSING:
            members[field.name] = field.default
        else:
            raise SystemExit(f"{where}: no `{field.name}`")
    return cls(**members)


def typed(kind: object, value: object, where: str) -> object:
    """`value` as `kind`: a dataclass from an object, a list element by element,
    a scalar of exactly that type (a JSON boolean is not an integer)."""
    if dataclasses.is_dataclass(kind):
        return of_json(kind, value, where)
    if typing.get_origin(kind) is list:
        if not isinstance(value, list):
            raise SystemExit(f"{where}: expected a list")
        (item,) = typing.get_args(kind)
        return [typed(item, v, f"{where}[{i}]") for i, v in enumerate(value)]
    if not isinstance(value, kind) or (kind is int and isinstance(value, bool)):
        raise SystemExit(f"{where}: expected {kind.__name__}")
    return value


# --- The Noir sources, read back ----------------------------------------------


@functools.cache
def constant(name: str, source: pathlib.Path = TABLE) -> str:
    """The right-hand side of `[pub] global <name>`, whitespace collapsed."""
    # nargo fmt wraps long constants, so read the declaration whole.
    found = re.search(rf"\bglobal\s+{re.escape(name)}\s*:[^=]*=\s*([^;]*);", source.read_text())
    if found is None:
        raise SystemExit(f"{source}: no `global {name}`; regenerate or check the name")
    return " ".join(found.group(1).split())


def integer(name: str, source: pathlib.Path = TABLE) -> int:
    return int(constant(name, source))


def byte_array(name: str, source: pathlib.Path = TABLE) -> bytes:
    inner = constant(name, source).strip("[]")
    return bytes(int(b, 16) for b in inner.split(",") if b.strip())


# --- Encodings the witness scripts share --------------------------------------


def fold(value: bytes) -> bytes:
    """A-Z down to a-z, every other byte unchanged: lib.nr's `fold_handle`."""
    return bytes(b + 0x20 if 0x41 <= b <= 0x5A else b for b in value)


def packed_tag(tag: bytes) -> int:
    """A tag as bearer-link's public input: its bytes from the top of a Field."""
    return int.from_bytes(tag.ljust(integer("MAX_TAG_LEN", LIB), b"\0"), "big")


def halves(digest: bytes) -> tuple[int, int]:
    """A 32-byte digest as the circuits' `[high, low]` 16-byte big-endian halves."""
    return int.from_bytes(digest[:16], "big"), int.from_bytes(digest[16:], "big")


def padded(name: str, value: bytes, size: int) -> list[int]:
    """`value` in a `size`-byte circuit buffer, the tail zero."""
    if len(value) > size:
        raise SystemExit(f"`{name}`: {len(value)} bytes do not fit the circuit's {size}-byte buffer")
    return list(value) + [0] * (size - len(value))


def toml_array(values, *, quoted: bool = False) -> str:
    """A Prover.toml array. Strings are always quoted, numbers when `quoted`."""
    return "[" + ", ".join(f'"{v}"' if quoted or isinstance(v, str) else str(v) for v in values) + "]"


def node(tag: str, value: str) -> str:
    """`SHA256(tag || value)` as the tables spell a node: 0x-hex."""
    return "0x" + hashlib.sha256((tag + value).encode()).hexdigest()


# --- platforms.json -------------------------------------------------------------

# A platform key names constants (`HANDLE_TAG_X`) and test functions (`handle_x_0`).
PLATFORM_KEY = re.compile(r"[a-z][a-z0-9_]*")
# A tag as a literal in Noir, Rust, TypeScript and Solidity alike: no quote,
# backslash or space.
TAG = re.compile(r"[A-Za-z0-9._~:/?#\[\]@!$&*+,;=%-]+")
ID_SHAPES = ("decimal", "string")


@dataclasses.dataclass(frozen=True)
class Platform:
    """One platform's node tags, the circuits' buffers for it and its id shape."""

    platform: str
    userIdTag: str
    handleTag: str
    maxHandle: int
    maxId: int
    idShape: str

    @property
    def name(self) -> str:
        """The constant-name fragment: `X` in `HANDLE_TAG_X`."""
        return self.platform.upper()

    @property
    def decimal_id(self) -> bool:
        return self.idShape == "decimal"

    def check(self, max_tag: int) -> None:
        """Refuse a value no circuit or consumer can carry: a key no identifier
        spells, a tag no literal holds or longer than `max_tag`, a buffer that
        is not a positive integer, an id shape the circuits lack."""
        if not PLATFORM_KEY.fullmatch(self.platform):
            raise SystemExit(f"ERROR: platform {self.platform!r} must be lowercase ASCII")
        for tag in (self.userIdTag, self.handleTag):
            if not TAG.fullmatch(tag):
                raise SystemExit(f"ERROR: tag {tag!r} carries a character a literal cannot hold")
            if len(tag.encode()) > max_tag:
                raise SystemExit(f"ERROR: tag {tag!r} must be 1 to {max_tag} bytes (lib.nr's MAX_TAG_LEN)")
        if self.idShape not in ID_SHAPES:
            raise SystemExit(f"ERROR: {self.platform!r} idShape {self.idShape!r} is not one of {ID_SHAPES}")
        for field in ("maxHandle", "maxId"):
            if getattr(self, field) <= 0:
                raise SystemExit(f"ERROR: {self.platform!r} {field} must be a positive integer")


@dataclasses.dataclass(frozen=True)
class PlatformTable:
    """lib/identity/platforms.json: every platform, in table order."""

    platforms: list[Platform]

    @classmethod
    def load(cls, path: pathlib.Path = PLATFORMS) -> PlatformTable:
        table = of_json(cls, json.loads(path.read_text(encoding="utf-8")), str(path))
        table.check()
        return table

    def check(self) -> None:
        """Refuse a key named twice, a platform that fails its own check, or
        two tags of which one is a prefix of the other: a node of one kind
        could then be a node of another."""
        max_tag = integer("MAX_TAG_LEN", LIB)
        seen: set[str] = set()
        for p in self.platforms:
            p.check(max_tag)
            if p.platform in seen:
                raise SystemExit(f"ERROR: {p.platform!r} appears twice")
            seen.add(p.platform)
        tags = [t for p in self.platforms for t in (p.userIdTag, p.handleTag)]
        for i, a in enumerate(tags):
            for b in tags[i + 1 :]:
                if a.startswith(b) or b.startswith(a):
                    raise SystemExit(f"ERROR: tags {a!r} and {b!r} overlap; tags must be distinct and prefix-free")

    def by_key(self) -> dict[str, Platform]:
        return {p.platform: p for p in self.platforms}


# --- handles.json ---------------------------------------------------------------

# Each refusal's Noir assertion message, after `handle ` or `id `.
NOIR_ERRORS = {
    "Empty": "is empty",
    "TooLong": "too long",
    "BadCharacter": "byte not allowed",
    "BadShape": "shape not allowed",
}
# The refusal only a decimal id can earn: its grammar is REQ-PLAT-06's.
DECIMAL_ONLY_ERROR = "BadShape"


@dataclasses.dataclass(frozen=True)
class ErrorKind:
    """One refusal the vectors name."""

    key: str
    note: str


@dataclasses.dataclass(frozen=True)
class HandleVector:
    """One handle case: an input the transform accepts, folded, with its node,
    or refuses with an error kind."""

    platform: str
    input: str
    output: str = ""
    error: str = ""
    handleNode: str = ""

    @property
    def accepted(self) -> bool:
        return not self.error

    def check(self, platform: Platform, errors: set[str]) -> None:
        """An accepted case's output is its input folded and its node is
        SHA256(tag || output); a refused case names a known error and carries
        neither."""
        folded = fold(self.input.encode()).decode()
        if self.accepted:
            if self.output != folded:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: output {self.output!r} is not its input folded")
            want = node(platform.handleTag, self.output)
            if self.handleNode != want:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: handleNode is not SHA256(tag || output); expected {want}")
        else:
            if self.error not in errors:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: unknown error kind {self.error!r}")
            if self.output or self.handleNode:
                raise SystemExit(f"ERROR: refused {self.platform} {self.input!r} carries an output or a node")


@dataclasses.dataclass(frozen=True)
class IdVector:
    """One id case: an input the id check accepts, with its node, or refuses
    with an error kind."""

    platform: str
    input: str
    error: str = ""
    idNode: str = ""

    @property
    def accepted(self) -> bool:
        return not self.error

    def check(self, platform: Platform, errors: set[str]) -> None:
        """An accepted case's node is SHA256(tag || input); a refused case
        names a known error, one a decimal id can earn, and carries none."""
        if self.accepted:
            want = node(platform.userIdTag, self.input)
            if self.idNode != want:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: idNode is not SHA256(tag || input); expected {want}")
        else:
            if self.error not in errors:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: unknown error kind {self.error!r}")
            if self.error == DECIMAL_ONLY_ERROR and not platform.decimal_id:
                raise SystemExit(f"ERROR: {self.platform} {self.input!r}: {self.error} needs a decimal id")
            if self.idNode:
                raise SystemExit(f"ERROR: refused {self.platform} {self.input!r} carries idNode")


@dataclasses.dataclass(frozen=True)
class HandleTable:
    """lib/identity/handles.json: the shared vectors, with the SHA-256 of the
    file's bytes, which every generated table carries."""

    version: int
    errors: list[ErrorKind]
    vectors: list[HandleVector]
    idVectors: list[IdVector]
    sha256: str = ""

    @classmethod
    def load(cls, platforms: PlatformTable, path: pathlib.Path = HANDLES) -> HandleTable:
        # Explicit encoding: the vectors hold non-ASCII, and the ambient locale
        # decides otherwise on a machine configured differently.
        raw = path.read_bytes()
        table = of_json(cls, json.loads(raw.decode("utf-8")), str(path))
        table = dataclasses.replace(table, sha256=hashlib.sha256(raw).hexdigest())
        table.check(platforms)
        return table

    def check(self, platforms: PlatformTable) -> None:
        """Every vector names a platform of the table and checks against it;
        every error kind has a Noir message."""
        by_key = platforms.by_key()
        errors = {e.key for e in self.errors}
        missing = errors - set(NOIR_ERRORS)
        if missing:
            raise SystemExit(f"ERROR: no Noir message for error kinds {sorted(missing)}; add them to NOIR_ERRORS")
        for vec in self.vectors + self.idVectors:
            if vec.platform not in by_key:
                raise SystemExit(f"ERROR: vector {vec.input!r} names {vec.platform!r}, which platforms.json lacks")
            vec.check(by_key[vec.platform], errors)


# --- The Noir -----------------------------------------------------------------

NOIR_ESCAPES = {0x09: "\\t", 0x0A: "\\n", 0x22: '\\"'}


def header() -> str:
    return "".join(f"// {line}\n" for line in BANNER)


def noir_bytes(value: bytes) -> str:
    return "[" + ", ".join(f"0x{b:02x}" for b in value) + "]"


def noir_string(value: bytes) -> str | None:
    """`value` as a Noir string literal, or None when it holds a byte a
    literal cannot spell plainly: a backslash, a control byte other than tab
    and newline, or anything above 0x7e."""
    out = []
    for b in value:
        if b in NOIR_ESCAPES:
            out.append(NOIR_ESCAPES[b])
        elif 0x20 <= b <= 0x7E and b != 0x5C:
            out.append(chr(b))
        else:
            return None
    return '"' + "".join(out) + '"'


def noir_halves(node_hex: str) -> str:
    """A node from the table as the `[high, low]` Fields `node_halves` returns."""
    return f"[0x{node_hex[2:34]}, 0x{node_hex[34:]}]"


def gen_table(platforms: PlatformTable, digest: str) -> str:
    """The circuit library's constants: what every circuit compiles against."""
    lines = [
        header().rstrip("\n"),
        "",
        "// Platform tags and buffers, for the identity circuits. The transform is",
        "// lib.nr's; table_tests.nr runs it against the shared vector table.",
        "",
        "/// SHA-256 of the handles.json this file was generated from.",
        f'pub global TABLE_SHA256: str<64> = "{digest}";',
        "",
    ]
    for p in platforms.platforms:
        id_tag = p.userIdTag.encode()
        handle_tag = p.handleTag.encode()
        lines += [
            f"/// `{p.userIdTag}`",
            f"pub global USER_ID_TAG_{p.name}: [u8; {len(id_tag)}] = {noir_bytes(id_tag)};",
            f"/// `{p.handleTag}`",
            f"pub global HANDLE_TAG_{p.name}: [u8; {len(handle_tag)}] = {noir_bytes(handle_tag)};",
            f"pub global MAX_HANDLE_{p.name}: u32 = {p.maxHandle};",
            f"pub global MAX_ID_{p.name}: u32 = {p.maxId};",
            f"pub global ID_DECIMAL_{p.name}: bool = {str(p.decimal_id).lower()};",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def gen_table_tests(platforms: PlatformTable, handles: HandleTable) -> str:
    """One Noir test per vector, run against lib.nr's algorithm.

    A refused vector is a `should_fail_with` test on the reason every other
    language gives. A value longer than the platform allows does not fit the
    circuit's buffer at all; its test hands the buffer's worth of bytes with
    the true length, which is the claim a dishonest witness would make.
    """
    by_key = platforms.by_key()
    lines = [
        header().rstrip("\n"),
        f"// Table SHA-256: {handles.sha256} (table::TABLE_SHA256).",
        "",
        "// The shared vector table, run against lib.nr's algorithm.",
        "",
        "use crate::{check_id, fixed_node_halves, fold_handle, node_halves, table, tag_of};",
        "use crate::testing::padded;",
        "",
    ]

    def buffer(value: bytes, size: int) -> list[str]:
        """The padded witness, as a string literal when one spells it."""
        kept = value[:size]
        literal = noir_string(kept)
        if literal is not None:
            return [f"    let raw: [u8; {size}] = padded({literal}.as_bytes());"]
        return [
            f"    // {json.dumps(value.decode(), ensure_ascii=False)}",
            f"    let raw: [u8; {size}] = {noir_bytes(kept + bytes(size - len(kept)))};",
        ]

    for i, vec in enumerate(handles.vectors):
        p = by_key[vec.platform]
        raw = vec.input.encode()
        attr = "#[test]"
        if not vec.accepted:
            attr = f'#[test(should_fail_with = "handle {NOIR_ERRORS[vec.error]}")]'
        lines.append(attr)
        lines.append(f"fn handle_{vec.platform}_{i}() {{")
        lines += buffer(raw, p.maxHandle)
        lines.append(f"    let out = fold_handle(raw, {len(raw)});")
        if vec.accepted:
            lines.append(f"    let (tag, tag_len) = tag_of(table::HANDLE_TAG_{p.name});")
            lines.append(
                f"    assert(node_halves(tag, tag_len, out, {len(raw)})"
                f" == {noir_halves(vec.handleNode)});"
            )
            lines.append(
                f"    assert(fixed_node_halves(table::HANDLE_TAG_{p.name}, out, {len(raw)})"
                f" == {noir_halves(vec.handleNode)});"
            )
        else:
            lines.append("    let _ = out;")
        lines.append("}")
        lines.append("")

    for i, vec in enumerate(handles.idVectors):
        p = by_key[vec.platform]
        raw = vec.input.encode()
        attr = "#[test]"
        if not vec.accepted:
            attr = f'#[test(should_fail_with = "id {NOIR_ERRORS[vec.error]}")]'
        lines.append(attr)
        lines.append(f"fn id_{vec.platform}_{i}() {{")
        lines += buffer(raw, p.maxId)
        lines.append(f"    check_id(raw, {len(raw)}, table::ID_DECIMAL_{p.name});")
        if vec.accepted:
            lines.append(f"    let (tag, tag_len) = tag_of(table::USER_ID_TAG_{p.name});")
            lines.append(
                f"    assert(node_halves(tag, tag_len, raw, {len(raw)})"
                f" == {noir_halves(vec.idNode)});"
            )
            lines.append(
                f"    assert(fixed_node_halves(table::USER_ID_TAG_{p.name}, raw, {len(raw)})"
                f" == {noir_halves(vec.idNode)});"
            )
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def formatted(files: dict[str, str]) -> dict[str, str]:
    """`files` (name -> Noir source) run through `nargo fmt` as one package,
    so what is compared or written is what CI's `nargo fmt --check` accepts."""
    nargo = shutil.which("nargo")
    if nargo is None:
        print("ERROR: nargo is not on PATH, so the Noir cannot be formatted", file=sys.stderr)
        raise SystemExit(1)
    with tempfile.TemporaryDirectory() as tmp:
        package = pathlib.Path(tmp)
        src = package / "src"
        src.mkdir()
        (package / "Nargo.toml").write_text(
            '[package]\nname = "table"\ntype = "lib"\nauthors = [""]\n[dependencies]\n'
        )
        (src / "lib.nr").write_text("".join(f"mod {name};\n" for name in files))
        for name, text in files.items():
            (src / f"{name}.nr").write_text(text, encoding="utf-8")
        done = subprocess.run([nargo, "fmt"], cwd=package, capture_output=True, text=True)
        if done.returncode != 0:
            print(f"ERROR: nargo fmt failed:\n{done.stderr}", file=sys.stderr)
            raise SystemExit(1)
        return {name: (src / f"{name}.nr").read_text(encoding="utf-8") for name in files}


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit non-zero when a generated file differs from its sources.",
    )
    args = parser.parse_args()

    platforms = PlatformTable.load()
    handles = HandleTable.load(platforms)
    generated = formatted({
        TABLE.stem: gen_table(platforms, handles.sha256),
        TABLE_TESTS.stem: gen_table_tests(platforms, handles),
    })
    outputs = [(TABLE, generated[TABLE.stem]), (TABLE_TESTS, generated[TABLE_TESTS.stem])]

    if args.check:
        stale = [
            path
            for path, text in outputs
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("ERROR: generated files differ from their sources. Run scripts/identity_table.py", file=sys.stderr)
            for path in stale:
                print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"lib/identity's table is what platforms.json and handles.json ({handles.sha256}) generate")
        return 0

    for path, text in outputs:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
